#!/usr/bin/env node
// tools/gen/arena_lucerne.js — builds hs_03 "The Heartwick" (final arena: LUCERNE, the Everlantern) with
// tools/lib/roomkit.js, exactly per design/world_plan.json, and emits src/data/arenas/lucerne.js. Owner: boss-lucerne.
//   node tools/gen/arena_lucerne.js [--print]
//
// Plan notes (hs_03, 64x36): single entrance W1 (col 0, rows 30-32). Floor top row 33 (rows 33-35 solid) flat across
// cols 1-62 (crystal spikes are her attack, not tiles). Phase-2 platforms (static one-way crystal platforms '='): tops
// at row 27 (cols 8-15, 48-55), row 21 (cols 20-27, 36-43) and row 15 (cols 28-35). The Everlantern cage (decor) fills
// the upper centre (rows 2-12, cols 20-43); ceiling rows 0-1 solid. arena_gate (w1,h4) at col 2 rows 29-32 under a
// solid lintel at row 28. arena: boss lucerne, bx 44, by 32, trigger cols 12-36 rows 22-32. After victory the ending
// plays (by sparks); no exit beyond W1.
// The Everlantern itself (cage, chains that hold the platform pyramid, crystal stilts under the low decks, the white
// First Flame, Lucerne waiting before it, and its state after the ending) is drawn by boss-lucerne's room script
// 'lucerne_heart' (src/entities/bosses/lucerne.js).
'use strict';
const path = require('path');
const RK = require(path.join(__dirname, '..', 'lib', 'roomkit'));

function hs03() {
  const r = RK.room('hs_03');                    // 64x36; W1 col 0 rows 30-32
  // The hall: air rows 2-32 across cols 3-62 (ceiling rows 0-1, floor rows 33-35 and the east wall col 63 stay solid).
  r.carve(3, 2, 60, 31);
  // West door: the arch tunnel (cols 0-2, rows 30-32) and the gate slot (col 2, row 29) under the solid lintel
  // (col 2, row 28); cols 0-2 above the lintel stay solid wall.
  r.openExits();
  r.carve(0, 30, 3, 3);
  r.carve(2, 29, 1, 1);
  // The platform pyramid (one-way crystal/gold decks, exact plan rows and columns).
  r.platform(8, 27, 8);
  r.platform(48, 27, 8);
  r.platform(20, 21, 8);
  r.platform(36, 21, 8);
  r.platform(28, 15, 8);

  // ---- encounter
  r.put(2, 32, { type: 'arena_gate', id: 'hs_ag3', w: 1, h: 4, side: 'right' });   // shuts behind the player
  r.add({ type: 'arena', boss: 'lucerne', bx: 44, by: 32, trigger: [12, 22, 36, 32], x: 24, y: 32 });
  // The Everlantern (backdrop + supports + Lucerne's waiting figure + the after-state), drawn behind the terrain.
  r.add({ type: 'event', script: 'lucerne_heart', x: 32, y: 12, w: 1, h: 1, z: -12 });

  // ---- dressing (back layer only; nothing that reads as a ledge or a hazard)
  for (const [c, flip] of [[5, false], [59, true]]) r.add({ type: 'decor', kind: 'stained_window', x: c, y: 32, flip, scale: 1.25, dim: 0.35, layer: 'back' });
  for (const c of [17, 46]) r.add({ type: 'decor', kind: 'stained_window', x: c, y: 32, scale: 1.1, dim: 0.5, layer: 'back' });
  for (const c of [7, 56]) r.add({ type: 'decor', kind: 'candelabra', x: c, y: 32, material: 'gold', flame: 'gold', lit: true, layer: 'back' });
  for (const [c, n] of [[12, 4], [24, 3], [40, 3], [52, 5]]) r.add({ type: 'decor', kind: 'candle_cluster', x: c, y: 32, count: n, flame: 'gold', lit: true, layer: 'back' });
  for (const c of [4, 61]) r.add({ type: 'decor', kind: 'statue_waxen', x: c, y: 32, variant: 1, material: 'gold', dim: 0.45, layer: 'back' });
  for (const c of [6, 58]) r.add({ type: 'decor', kind: 'banner', x: c, y: 2, len: 150, color: '#c8a050', layer: 'back' });
  // lights: the door, the floor candles, the deck lamps (the Everlantern's own light comes from the room script)
  r.add({ type: 'light', x: 4, y: 30, r: 4, color: '#ffd890', intensity: 0.45, flicker: true });
  r.add({ type: 'light', x: 7, y: 30, r: 5, color: '#ffcf70', intensity: 0.4, flicker: true });
  r.add({ type: 'light', x: 56, y: 30, r: 5, color: '#ffcf70', intensity: 0.4, flicker: true });
  r.add({ type: 'light', x: 12, y: 25, r: 6, color: '#ffe2a0', intensity: 0.25 });
  r.add({ type: 'light', x: 52, y: 25, r: 6, color: '#ffe2a0', intensity: 0.25 });
  r.add({ type: 'light', x: 32, y: 29, r: 10, color: '#ffe8b0', intensity: 0.22 });
  return r;
}

const r = hs03();
const { errors, warnings } = r.check();
for (const w of warnings) console.log('warning: ' + w);
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }
const def = r.toDef({ theme: { bg: 'interior', decor: 0.35, fg: false, landmark: false }, bgSeed: 31, dark: 0.45 });
const out = RK.emit('sanctum', [def], 'src/data/arenas/lucerne.js', "arena hs_03 (LUCERNE, the Everlantern) — generated by tools/gen/arena_lucerne.js");
console.log('wrote ' + path.relative(path.join(__dirname, '..', '..'), out));
if (process.argv.includes('--print')) console.log(r.ascii());
